#!/usr/bin/env python3
"""The capitol lower bound for the official 11x11 -- a THIN WRAPPER around the engine.

This file used to re-implement the hitting-set logic of src/hitting.py, and the copy was
broken in five different ways (missing parenthesis, an undefined DATA, an unclosed
json.dump, an output path that wrote "w" inside os.path.join, and a dead filter).  It had
never run.  The rule of this repository is that the engine is the single source of truth,
so this script now only CALLS the engine and writes down what it says.

The derived JSON in data/derived/ is regenerated by this script, and
tools/run_all_gates.py checks that the committed file still matches the engine.

Exit code 0 = the engine ran and the numbers are as expected.
"""

from __future__ import annotations

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
sys.path.insert(0, os.path.join(ROOT, "src"))

from hitting import min_hitting_set, packing_bound, split_demands      # noqa: E402

PUZZLE = os.path.join(ROOT, "data", "puzzles", "official-11x11", "puzzle.json")
OUT = os.path.join(ROOT, "data", "derived", "capitol_hitting_set_11x11.json")

ok = True


def chk(cond, msg):
    global ok
    print(("  PASS  " if cond else "  FAIL  ") + msg)
    ok = ok and bool(cond)


def main() -> int:
    with open(PUZZLE) as fh:
        puz = json.load(fh)
    n = puz["size"]
    # the hints are 0-based (data/schema/puzzle.schema.json)
    hints = {(h["row"], h["col"]): h["value"] for h in puz["hints"]}

    uncovered, satisfied = split_demands(n, hints)
    min_extra, min_sets = min_hitting_set(uncovered)
    pack = packing_bound(uncovered)
    known = {c for c, v in hints.items() if v == 0}

    print("=== the 11x11 capitol bound, computed by src/hitting.py ===")
    chk(len(hints) == 33, f"33 hints (got {len(hints)})")
    chk(len(satisfied) == 22, f"22 demands already covered by a revealed capitol "
                              f"(got {len(satisfied)})")
    chk(len(uncovered) == 9, f"9 uncovered demands (got {len(uncovered)})")
    pool = sorted({c for _, _, _, C in uncovered for c in C})
    chk(len(pool) == 64, f"64 candidate cells for hidden capitols (got {len(pool)})")
    chk(min_extra == 4, f"at least 4 hidden capitols (got {min_extra})")
    chk(len(min_sets) == 120, f"120 minimum hitting sets (got {len(min_sets)})")
    chk(pack == 4, f"the packing (dual) bound also says 4 (got {pack})")
    chk(len(known) + min_extra == 6, f"at least 6 capitols in total "
                                     f"(got {len(known) + min_extra})")

    # the committed derived file must agree with the engine
    if os.path.exists(OUT):
        with open(OUT) as fh:
            old = json.load(fh)
        same = (old.get("min_additional") == min_extra
                and old.get("n_min_sets") == len(min_sets)
                and old.get("demands") == len(uncovered)
                and old.get("satisfied_by_known") == len(satisfied)
                and old.get("pool") == len(pool))
        chk(same, "data/derived/capitol_hitting_set_11x11.json still matches the engine")
    else:
        chk(False, "data/derived/capitol_hitting_set_11x11.json exists")

    print("\nRESULT:", "ALL CHECKS PASSED" if ok else "FAILURES PRESENT")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
